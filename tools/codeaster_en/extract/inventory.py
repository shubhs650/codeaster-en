"""``caen extract inventory``: Tier coverage and astest usage → ``docs/INVENTORY.md``.

Task 1.5. Everything is computed from data already extracted into ``en/`` (no ``upstream/``
access, no solver):

- ``en/commands/*.json`` (``caen extract catalog``) for commands and keywords;
- ``en/messages/*.en.json`` (``caen extract messages``) for message families;
- ``en/astest-index.json`` (``caen extract astest-index``) for test-case usage;
- ``docs/COMMAND-SET.md`` for the Tier 1/2/3 command lists, their "key keywords" and the
  Tier 1 message families.

The result is Markdown written between two marker comments in ``docs/INVENTORY.md``; the rest
of that file is hand-written and left alone. Re-run after any of the three extractors or after
editing COMMAND-SET.md; ``tests/test_inventory.py`` fails while the block is stale.

How COMMAND-SET.md is read. In each Tier 1/2 table row, every upper-case identifier in a
backtick span of the *Command* column that is a known command is one of the row's commands;
every other identifier in the *Command* and *Key keywords* columns is a key keyword of the row.
A key keyword is *found* when it is a keyword name (``SIMP``/``FACT``) or a string in an
``into=`` list of one of the row's commands, or is itself a command. Tier 3 is every
backticked name of its paragraph (all taken as commands). Tier 1 message families are the
backticked names after "Likely:".

Message heuristics (the plan asks for "family name heuristics"; both are only hints, a message
can be emitted by any command):

- *family name*: a family whose name without its trailing number equals the command name
  without underscores (``AFFE_CARA_ELEM`` → ``AFFECARAELEM``, ``CALC_CHAMP`` → ``CALCCHAMP``);
- *mentions*: messages whose French text contains the command name as a whole word.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from codeaster_en.extract.catalog import iter_keywords

INVENTORY_RELPATH = Path("docs/INVENTORY.md")
COMMAND_SET_RELPATH = Path("docs/COMMAND-SET.md")
COMMANDS_RELDIR = Path("en/commands")
MESSAGES_RELDIR = Path("en/messages")
ASTEST_INDEX_RELPATH = Path("en/astest-index.json")

BEGIN = "<!-- caen:inventory:begin (generated by `caen extract inventory`; do not edit) -->"
END = "<!-- caen:inventory:end -->"

TOP_N = 50
TIERS = ("1", "2", "3")

_BACKTICK = re.compile(r"`([^`]+)`")
_IDENT = re.compile(r"(?<![A-Za-z0-9_])([A-Z][A-Z0-9_]*[A-Z0-9])(?![A-Za-z0-9_*])")
_TIER_HEADING = re.compile(r"^## Tier ([0-9])\b")
_FAMILY_NUMBER = re.compile(r"[0-9]+$")


@dataclass
class Row:
    """One Tier 1/2 table row of COMMAND-SET.md (or the Tier 3 paragraph)."""

    tier: str
    function: str
    commands: list[str]
    key_keywords: list[str] = field(default_factory=list)


@dataclass
class CommandSet:
    rows: list[Row]
    message_families: list[str]


def _idents(text: str) -> list[str]:
    out: list[str] = []
    for span in _BACKTICK.findall(text):
        for name in _IDENT.findall(span):
            if name not in out:
                out.append(name)
    return out


def parse_command_set(text: str, known: set[str]) -> CommandSet:
    """Tier rows and Tier 1 message families from COMMAND-SET.md."""
    rows: list[Row] = []
    families: list[str] = []
    tier: str | None = None
    for line in text.splitlines():
        heading = _TIER_HEADING.match(line)
        if heading:
            tier = heading.group(1)
            continue
        if line.startswith("## "):
            tier = None
            continue
        if tier is None:
            continue
        if line.startswith("Likely:") and tier == "1":
            families = _idents(line)
        elif line.startswith("|") and tier in ("1", "2"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) < 3 or set(cells[0]) <= {"-", ":", " "} or cells[1] == "Command":
                continue
            names = _idents(cells[1])
            commands = [n for n in names if n in known]
            keywords = [n for n in names if n not in known]
            keywords += [n for n in _idents(cells[2]) if n not in keywords]
            rows.append(Row(tier, cells[0], commands, keywords))
        elif tier == "3" and "`" in line:
            rows.append(Row(tier, "Later", _idents(line)))
    return CommandSet(rows, families)


def _load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def load_commands(directory: Path) -> dict[str, dict[str, Any]]:
    return {p.stem: _load_json(p) for p in sorted(directory.glob("*.json"))}


def load_messages(directory: Path) -> dict[str, dict[str, Any]]:
    return {
        p.name.removesuffix(".en.json"): _load_json(p) for p in sorted(directory.glob("*.en.json"))
    }


def family_base(family: str) -> str:
    """``MECANONLINE10`` → ``MECANONLINE``; ``POST0`` → ``POST``."""
    return _FAMILY_NUMBER.sub("", family)


@dataclass
class CommandStats:
    kind: str
    simple: int
    factor: int
    bloc: int
    with_fr: int
    names: set[str]
    into: set[str]


def command_stats(doc: dict[str, Any]) -> CommandStats:
    kinds: Counter[str] = Counter()
    names: set[str] = set()
    into: set[str] = set()
    with_fr = 0
    for kw in iter_keywords(doc.get("keywords", [])):
        kinds[kw["kind"]] += 1
        if kw["kind"] == "bloc":
            continue
        names.add(kw["name"])
        if kw.get("fr"):
            with_fr += 1
        for value in kw.get("into") or []:
            if isinstance(value, str):
                into.add(value)
    return CommandStats(
        doc["kind"], kinds["simple"], kinds["factor"], kinds["bloc"], with_fr, names, into
    )


def _fmt_list(items: list[str], limit: int = 0) -> str:
    shown = items if not limit or len(items) <= limit else items[:limit]
    text = ", ".join(f"`{i}`" for i in shown)
    if shown is not items:
        text += f", … (+{len(items) - limit})"
    return text or "—"


def _table(header: list[str], rows: list[list[str]], align: str) -> list[str]:
    out = ["| " + " | ".join(header) + " |"]
    out.append("|" + "|".join("---:" if a == "r" else "---" for a in align) + "|")
    out.extend("| " + " | ".join(r) + " |" for r in rows)
    return out


def build(repo: Path) -> str:
    """The generated Markdown block (without markers)."""
    commands = load_commands(repo / COMMANDS_RELDIR)
    messages = load_messages(repo / MESSAGES_RELDIR)
    index = _load_json(repo / ASTEST_INDEX_RELPATH)
    usage: dict[str, dict[str, Any]] = index["commands"]
    known = set(commands) | set(usage)
    cset = parse_command_set((repo / COMMAND_SET_RELPATH).read_text(encoding="utf-8"), known)
    stats = {name: command_stats(doc) for name, doc in commands.items()}

    ranked = sorted(usage, key=lambda c: (-len(usage[c]["testcases"]), -usage[c]["calls"], c))
    rank = {c: i + 1 for i, c in enumerate(ranked)}

    gen = index["_generated_from"]
    lines: list[str] = [
        f"- **Data:** `en/commands/` ({len(commands)} files), `en/messages/` "
        f"({len(messages)} files), `en/astest-index.json`, all extracted from upstream "
        f"`{gen['upstream']}` (commit `{gen['upstream_commit'][:7]}`); tiers from "
        "`docs/COMMAND-SET.md`.",
        "- **Regenerate:** `caen extract inventory` (rewrites only this block).",
        "",
    ]

    # 7.1 Totals
    kinds = Counter(s.kind for s in stats.values())
    total = Counter()
    for s in stats.values():
        total.update(simple=s.simple, factor=s.factor, bloc=s.bloc, fr=s.with_fr)
    n_msgs = sum(len(f["messages"]) for f in messages.values())
    bases = {family_base(f) for f in messages}
    summary = index["summary"]
    lines += ["### 7.1 Totals", ""]
    lines += _table(
        ["Item", "Count"],
        [
            [
                "Catalog commands",
                f"{len(commands)} ("
                + ", ".join(f"{v} `{k}`" for k, v in sorted(kinds.items()))
                + ")",
            ],
            ["Keyword occurrences (`SIMP` + `FACT`)", f"{total['simple'] + total['factor']}"],
            ["… with a `fr=` help string", f"{total['fr']}"],
            ["Conditional blocks (`BLOC`)", f"{total['bloc']}"],
            ["Message families (files)", f"{len(messages)}"],
            ["Message families (name without trailing number)", f"{len(bases)}"],
            ["Messages", f"{n_msgs}"],
            ["Test cases (`astest/*.export`)", f"{summary['testcases']}"],
            ["Command files parsed", f"{summary['command_files']}"],
            [
                "Commands used by at least one test case",
                f"{summary['commands_used']} of {summary['known_commands']}",
            ],
        ],
        "lr",
    )

    # 7.2 Tier commands
    lines += [
        "",
        "### 7.2 Tier commands",
        "",
        "Keyword counts are occurrences in the command's tree (a keyword repeated in several "
        "blocs counts each time). *Cases* = test cases that call the command; *rank* = its "
        "position among all commands by cases.",
        "",
    ]
    tiers_of: dict[str, list[str]] = {}
    for row in cset.rows:
        for cmd in row.commands:
            if row.tier not in tiers_of.setdefault(cmd, []):
                tiers_of[cmd].append(row.tier)
    rows: list[list[str]] = []
    for cmd, tiers in tiers_of.items():
        use = usage.get(cmd, {"testcases": [], "calls": 0})
        s = stats.get(cmd)
        if s is None:
            source = use.get("source")
            cat = f"not in catalog (`{source}`)" if source else "**not found**"
            kw = fr = blocs = "—"
        else:
            cat, kw, fr, blocs = s.kind, str(s.simple + s.factor), str(s.with_fr), str(s.bloc)
        rows.append(
            [
                ", ".join(tiers),
                f"`{cmd}`",
                cat,
                kw,
                fr,
                blocs,
                str(len(use["testcases"])),
                str(use["calls"]),
                str(rank.get(cmd, "—")),
            ]
        )
    lines += _table(
        ["Tier", "Command", "Catalog", "Keywords", "with `fr=`", "Blocs", "Cases", "Calls", "Rank"],
        rows,
        "llrrrrrrr",
    )
    lines.append("")
    for tier in TIERS:
        cmds = [c for c, t in tiers_of.items() if t[0] == tier]
        missing = [c for c in cmds if c not in commands]
        lines.append(
            f"- Tier {tier}: {len(cmds)} commands first listed in this tier, "
            f"{len(cmds) - len(missing)} in the catalog"
            + (f"; not in the catalog: {_fmt_list(missing)}." if missing else ".")
        )

    # 7.3 Key keywords
    lines += [
        "",
        "### 7.3 Key keywords named in COMMAND-SET.md",
        "",
        "A key keyword is *found* when it is a keyword name, an `into=` value, or a command "
        "name in one of the row's commands.",
        "",
    ]
    kw_rows: list[list[str]] = []
    n_found = n_all = 0
    for row in cset.rows:
        if not row.key_keywords:
            continue
        pool_names: set[str] = set()
        pool_into: set[str] = set()
        for cmd in row.commands:
            if cmd in stats:
                pool_names |= stats[cmd].names
                pool_into |= stats[cmd].into
        missing = [
            k
            for k in row.key_keywords
            if k not in pool_names and k not in pool_into and k not in known
        ]
        n_all += len(row.key_keywords)
        n_found += len(row.key_keywords) - len(missing)
        kw_rows.append(
            [
                row.tier,
                row.function,
                _fmt_list(row.commands),
                f"{len(row.key_keywords) - len(missing)}/{len(row.key_keywords)}",
                _fmt_list(missing),
            ]
        )
    lines += _table(["Tier", "Function", "Commands", "Found", "Not found"], kw_rows, "lllrl")
    lines += ["", f"{n_found} of {n_all} key keywords found."]

    # 7.4 Message families
    by_base: dict[str, list[str]] = {}
    for fam in messages:
        by_base.setdefault(family_base(fam), []).append(fam)
    lines += [
        "",
        '### 7.4 Tier 1 message families (COMMAND-SET.md "Likely" list)',
        "",
        "A listed name matches every file whose name without its trailing number equals it "
        "(`MODELISA` → `MODELISA`, `MODELISA2`…`MODELISA10`).",
        "",
    ]
    fam_rows = []
    for name in cset.message_families:
        files = by_base.get(name, [])
        count = sum(len(messages[f]["messages"]) for f in files)
        fam_rows.append([f"`{name}`", "yes" if files else "**no**", str(len(files)), str(count)])
    lines += _table(["Family", "Exists", "Files", "Messages"], fam_rows, "llrr")

    # 7.5 Messages referencing Tier 1/2 commands
    texts = [
        (fam, m["fr"]) for fam, doc in sorted(messages.items()) for m in doc["messages"].values()
    ]
    lines += [
        "",
        "### 7.5 Messages that reference Tier 1/2 commands",
        "",
        "*Family by name*: families named after the command (name without underscores, "
        "trailing number ignored). *Mentions*: messages whose French text contains the "
        "command name as a whole word, with the families holding most of them. Both are "
        "heuristics: they show where a command's own diagnostics live, not every message it "
        "can raise.",
        "",
    ]
    ref_rows = []
    for cmd in sorted({c for r in cset.rows if r.tier in ("1", "2") for c in r.commands}):
        own = by_base.get(cmd.replace("_", ""), [])
        own_n = sum(len(messages[f]["messages"]) for f in own)
        word = re.compile(rf"(?<![A-Za-z0-9_]){re.escape(cmd)}(?![A-Za-z0-9_])")
        hits = Counter(fam for fam, fr in texts if word.search(fr))
        top = [f"`{f}` {n}" for f, n in sorted(hits.items(), key=lambda x: (-x[1], x[0]))[:3]]
        ref_rows.append(
            [
                f"`{cmd}`",
                (_fmt_list(own) + f" ({own_n})") if own else "—",
                str(sum(hits.values())),
                ", ".join(top) or "—",
            ]
        )
    lines += _table(
        ["Command", "Family by name (messages)", "Mentions", "Top families"], ref_rows, "llrl"
    )

    # 7.6 Top-N
    lines += [
        "",
        f"### 7.6 Top {TOP_N} commands across astest",
        "",
        "Ranked by number of test cases that call the command, then by number of calls.",
        "",
    ]
    top_rows = []
    for cmd in ranked[:TOP_N]:
        use = usage[cmd]
        top_rows.append(
            [
                str(rank[cmd]),
                f"`{cmd}`",
                str(len(use["testcases"])),
                str(use["calls"]),
                ", ".join(tiers_of.get(cmd, ["—"])),
            ]
        )
    lines += _table(["Rank", "Command", "Cases", "Calls", "Tier"], top_rows, "rlrrl")
    untiered = [c for c in ranked[:TOP_N] if c not in tiers_of]
    lines += [
        "",
        f"In the top {TOP_N} but in no tier ({len(untiered)}): {_fmt_list(untiered)}.",
    ]
    return "\n".join(lines) + "\n"


def splice(document: str, block: str) -> str:
    """Replace the text between the markers (both must be present, in order)."""
    start = document.find(BEGIN)
    end = document.find(END)
    if start < 0 or end < start:
        raise ValueError(f"markers not found; the file must contain {BEGIN!r} then {END!r}")
    head = document[: start + len(BEGIN)]
    return f"{head}\n{block}{document[end:]}"


def write(repo: Path, out: Path | None = None) -> Path:
    path = out or repo / INVENTORY_RELPATH
    path.write_text(splice(path.read_text(encoding="utf-8"), build(repo)), encoding="utf-8")
    return path
